const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');
const { sensitivePath, inspect } = require('./check-secrets.cjs');
for (const file of ['.env', '.env.local', 'config/production.env', '.envrc', 'cert.pem', 'private.key', 'signing.pfx', 'account.p12', 'credentials.json', 'service-account-prod.json']) assert(sensitivePath(file), file);
for (const file of ['.env.example', 'package.json', 'src/keys.ts', 'README.md']) assert(!sensitivePath(file), file);
assert.equal(inspect('.env.example', Buffer.from('API_KEY=replace-me\n')).length, 0);
const token = 'ghp' + '_' + 'A'.repeat(36);
assert(inspect('src/config.ts', Buffer.from(token)).some(hit => hit.rule === 'github-token'));
assert(inspect('.env.example', Buffer.from(token)).length, 'Example files still need content checks');
assert(inspect('notes.txt', Buffer.from('-----BEGIN ' + 'PRIVATE KEY-----')).some(hit => hit.rule === 'private-key'));
assert(inspect('config.json', Buffer.from('"client_secret": "' + 'x'.repeat(24) + '"')).some(hit => hit.rule === 'literal-credential'));
const hits = JSON.stringify(inspect('sample.ts', Buffer.from(token)));
assert(!hits.includes(token), 'Diagnostics must not expose the matched value');
assert.deepEqual(inspect('src/keys.ts', Buffer.from('const token = `p${serial}`;\n')), []);
fs.mkdirSync('test-results', { recursive: true });
const fixture = fs.mkdtempSync(path.resolve('test-results/secret-check-'));
execFileSync('git', ['init', '--quiet'], { cwd: fixture });
fs.writeFileSync(path.join(fixture, '.env'), 'EXAMPLE=value\n');
execFileSync('git', ['add', '--', '.env'], { cwd: fixture });
const result = spawnSync(process.execPath, [path.resolve(__dirname, 'check-secrets.cjs'), '--staged'], { cwd: fixture, encoding: 'utf8' });
assert.equal(result.status, 1, 'A staged environment file must block the check');
assert(result.stderr.includes('sensitive-filename'));
console.log('OK: secret filenames, templates, credentials in code, private keys, redacted diagnostics and staged Git objects');
